function product(
  id: string,
  name: string,
  category: string,
  price: number,
  portion: string,
  description: string,
  extras?: Partial<Product>,
): Product {
  const descLower = description.toLowerCase();
  const nameLower = name.toLowerCase();
  const isSpicy =
    descLower.includes("остр") ||
    descLower.includes("спайси") ||
    descLower.includes("чили") ||
    descLower.includes("динамит") ||
    nameLower.includes("спайси") ||
    nameLower.includes("динамит");
  const isVegetarian =
    (category === "Спринг-роллы" && nameLower.includes("вегетарианск")) ||
    (category === "Вок и лапша" && nameLower.includes("овощами")) ||
    nameLower.includes("огурц") ||
    category === "Соусы и добавки";
  const isPopular =
    category === "Сеты" ||
    nameLower.includes("калифорния") ||
    nameLower.includes("филадельфия") ||
    nameLower.includes("токио") ||
    nameLower.includes("цезарь");

  return {
    id,
    name,
    category,
    price,
    portion,
    description,
    image: extras?.image || categoryImages[category] || categoryImages["Классические роллы"],
    isSpicy: extras?.isSpicy ?? isSpicy,
    isPopular: extras?.isPopular ?? isPopular,
    isVegetarian: extras?.isVegetarian ?? isVegetarian,
    japaneseName: extras?.japaneseName,
    allergens: extras?.allergens ?? (
      isVegetarian
        ? ["Глютен", "Кунжут"]
        : ["Морепродукты", "Сливочный сыр", "Глютен", "Кунжут"]
    ),
    calories: extras?.calories ?? (category === "Сеты" ? 820 : 310),
    ...extras,
  };
}

